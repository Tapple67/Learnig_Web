export const SUMMARY_PROMPT_VERSION = "summary.v6";

export function buildSummaryPrompt(input: {
  title: string;
  week: number;
  pages: { page: number; pdfText: string; note: string; noteSignals?: unknown }[];
}) {
  return `
너는 학습 정리 도우미다.
PDF 텍스트와 사용자 메모를 바탕으로 한국어 요약본을 작성하라.

규칙:
1) 사실 근거는 PDF 텍스트를 우선한다.
2) 사용자 메모는 별도 섹션으로 드러내지 말고, 각 개념 설명의 깊이와 쉬운 설명 여부에 자연스럽게 반영한다.
3) 같은 개념에 대한 메모가 많거나 어렵다는 신호가 있으면 해당 개념 설명을 조금 더 자세히 쓴다.
4) 쉽게 설명 요청이나 헷갈림 신호가 있으면 해당 개념 아래에 "쉽게 풀어보면:" 문장을 1개 추가한다.
5) 메모 내용이 PDF에서 검증되지 않으면 "메모 기반(원문 검증 불가)"라고 짧게 표시한다.
6) 단순 문장 나열을 피하고, 큰 주제 안에 하위 개념과 설명이 들어가도록 구조화한다.
7) 퀴즈, 시험, 학습 포인트 같은 평가용 섹션을 만들지 말고 요약 자체에 집중한다.
8) 가능한 경우 각 설명 끝에 (p.페이지번호)를 붙인다.
9) 출력은 반드시 한국어로만 작성한다.
10) 표 형태처럼 개념명과 설명을 같은 줄에 빽빽하게 붙이지 말고, 개념명을 먼저 쓰고 바로 아랫줄에 설명을 쓴다.
11) 공간을 충분히 써도 되므로 가독성을 우선한다. 한 항목이 길면 설명을 2문장으로 나누어도 된다.

출력 형식:
# ${input.week}주차 요약: ${input.title}

## 1. 큰 주제명

- **하위 개념명**
  PDF에서 말하는 핵심 내용을 1~2문장으로 설명한다. 필요하면 관련 개념과의 관계도 함께 설명한다. (p.?)

- 쉽게 풀어보면:
  어려운 개념을 일상적인 말로 다시 설명한다. 이 줄은 필요한 경우에만 쓴다. (p.?)

- **하위 개념명**
  ...

## 2. 큰 주제명

- **하위 개념명**
  ...

- 쉽게 풀어보면:
  ...

입력 페이지(JSON):
${JSON.stringify(input.pages, null, 2)}
`.trim();
}
